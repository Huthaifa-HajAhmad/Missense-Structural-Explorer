/**
 * The input every surface builds from an analysis result, in ONE place.
 *
 * Four surfaces (Population tab, its rail, Insights, the report) each spelled these eleven fields out
 * by hand and had already drifted: two read `insights.acmgCriteria` as a fallback and two did not, so
 * the same payload could report different engine criteria on different screens. New inputs — the locus
 * trail, the All of Us lookup — would have had to be added four times; now they are added here.
 */
export function frequencyEvidenceInputFromResult(
  result: FrequencyResultLike,
  overrides: Partial<FrequencyEvidenceInput> = {},
): FrequencyEvidenceInput {
  return {
    gnomadFrequency: result.gnomadFrequency ?? null,
    aouFrequency: result.aouFrequency ?? null,
    aouLookup: result.aouLookup ?? null,
    serviceStatus: result.serviceStatus ?? result.metadata?.serviceStatus ?? null,
    clinvar: result.clinvar
      ? { classification: result.clinvar.classification, alleleFrequencies: result.clinvar.alleleFrequencies }
      : null,
    assembly: result.predictorData?.gnomadVariantAssembly ?? null,
    pli: result.gnomadConstraint?.pli ?? null,
    engineCriteria: result.ruleBasedInsights?.acmgCriteria ?? result.insights?.acmgCriteria ?? null,
    acmgWeighting: result.metadata?.acmgWeighting ?? null,
    locus: { predictorData: result.predictorData ?? null, coordinateLift: result.coordinateLift ?? null },
    ...overrides,
  };
}

/** gnomAD's display name in the fallback sentence. */
const GNOMAD_DISPLAY = "gnomAD r4";

/**
 * Whether gnomAD was refused because the run's locus is a fallback, and the sentence that says so.
 * Null when the locus is not a fallback — the build gate's own wording then stands, and is true.
 */
function fallbackRefusal(input: FrequencyEvidenceInput): { sentence: string; retryable: boolean; recoveryAction: FrequencyEvidence["recoveryAction"] } | null {
  if (!isFallbackLocus(input.locus)) return null;
  const recoveryAction = locusRecoveryAction(input.locus);
  const retryable = recoveryAction === "retry";
  const failureKind = locusFailureKind(input.locus);
  return { sentence: fallbackLocusSentence(GNOMAD_DISPLAY, input.assembly ?? null, { retryable, failureKind: failureKind ?? undefined }), retryable, recoveryAction };
}

/** Percentage formatting for criterion sentences: `0.0001` → `"0.01%"`. */
function pct(value: number, digits: number): string {
  return `${(value * 100).toFixed(digits)}%`;
}

/**
 * A number, or `null` for anything that is not one.
 *
 * The contract types these fields as `number | null`, but the shapes actually on the wire include
 * `undefined` (an omitted optional key in a cached payload) and `NaN`/`Infinity` (an arithmetic
 * result the server did not guard). Reading any of them as a magnitude produces a classification
 * from a broken measurement, so every numeric input to this module goes through here.
 */
function finite(value: unknown): number | null {
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}

/**
 * A frequency as a display string, using enough significant digits to distinguish the values the
 * ACMG cut-points separate.
 *
 * The PM2 boundary (0.01%) is four orders of magnitude below the BA1 boundary (5%), so a single
 * fixed precision either renders every common variant as "0.0%" or the rare ones as scientific
 * noise. Exponential notation is used at and below the PM2 ceiling, which is also how the ClinVar
 * and gnomAD records themselves report these values.
 */
export function formatAlleleFrequency(af: number | null | undefined): string {
  const value = finite(af);
  if (value === null) return "—";
  if (value === 0) return "0";
  if (value < 0.0001) return value.toExponential(2);
  if (value < 0.01) return `${(value * 100).toFixed(3)}%`;
  return `${(value * 100).toFixed(2)}%`;
}

/** `1234567` → `"1,234,567"`, and a non-number → `"—"` so a missing denominator is never a zero. */
export function formatCount(value: number | null | undefined): string {
  const count = finite(value);
  if (count === null) return "—";
  return count.toLocaleString("en-US");
}

/**
 * The reading a rare-disease reviewer acts on, and the reading the rule acted on — kept as two
 * named things because they are frequently NOT the same number.
 *
 * `mostCopies` answers "how many people carry this, in the cohort that saw the most". `ruleAf`
 * answers "what did PM2/BS1/BA1 actually threshold on", which is gnomAD's ancestry-grouped maximum
 * far more often than it is any dataset's global figure — and the payload carries NO allele count
 * for that group (`GnomadFrequencyData` holds `groupMaxAF` and nothing else about the group).
 *
 * The reason both are exposed rather than one: printing the busiest cohort's `AC · AN` directly
 * above the grouped maximum's frequency implies the second divides out of the first. For CNNM2
 * p.Ser489Cys that implied quotient is 1.2e-5 against a stated 0.031% — a 26× gap that alone moves
 * the variant between PM2 and "between the cut-points". A surface must therefore label each line
 * with what it is, and `governs` tells it when the two really are one reading.
 */
export interface PopulationReading {
  /** The cohort reporting the most copies, or `null` when none reported interpretable counts. */
  mostCopies: { label: string; counts: string; af: number | null } | null;
  /** True when `mostCopies` is the very reading the rule classified on. */
  governs: boolean;
  /** The frequency the rule classified on, or `null` when it had nothing to classify. */
  ruleAf: number | null;
  /** Where `ruleAf` came from, in the words every surface sharing this module must use. */
  ruleSource: string;
}

/**
 * The counts a row leads with: `null` unless the source reports BOTH an allele count and a usable
 * allele number. A count with no denominator is not a measurement of anything comparable, and an
 * uninterpretable one must never become a screen's headline figure — the row still shows it, with
 * the reason its frequency is missing.
 */
export function formatAlleleCounts(observation: Pick<FrequencyObservation, "ac" | "an">): string | null {
  const parts: string[] = [];
  if (observation.ac !== null) parts.push(`AC ${formatCount(observation.ac)}`);
  if (observation.an !== null) parts.push(`AN ${formatCount(observation.an)}`);
  return parts.length > 0 ? parts.join(" · ") : null;
}

/** Where the rule's frequency came from, named so the number can be traced to a dataset. */
export function frequencySourceLabel(evidence: FrequencyEvidence): string {
  const { sourceId, usedGroupMax, fallback, absent } = evidence.criterion;
  // A recorded absence has no statistic behind it; naming "the global maximum" invented one.
  if (sourceId === "gnomad-group" && absent) return "gnomAD — no record (absence read as 0)";
  if (sourceId === "gnomad-group") {
    const base = usedGroupMax ? "gnomAD ancestry-grouped maximum" : "gnomAD global maximum";
    return fallback ? `${base} (fell back to the global maximum)` : base;
  }
  if (sourceId === "clinvar-submissions") return "ClinVar-submitted frequency";
  return "No source";
}

/**
 * The full reading pair. See {@link PopulationReading} for why the two halves are never merged.
 *
 * Only a source whose own availability is `available` competes: a faulted or pending fetch can leave
 * stale counts on an observation, and those are a fact about the run, not about the variant. The
 * local dbNSFP ingest reports `AC 0 · AN 0` for a combined cohort it did not measure, so a zero
 * denominator is excluded with it. Ties on the count break toward the LARGER denominator, which is
 * the conservative direction — the rarer-looking reading loses.
 */
export function populationReading(evidence: FrequencyEvidence): PopulationReading {
  const ruleAf = evidence.criterion.af;
  const pool = evidence.observations.filter(
    o => o.ac !== null && o.an !== null && o.an > 0 && o.availability.state === "available",
  );
  const top = pool.reduce<FrequencyObservation | null>(
    (best, o) =>
      best === null ? o
      : (o.ac ?? 0) > (best.ac ?? 0) ? o
      : (o.ac ?? 0) === (best.ac ?? 0) && (o.an ?? 0) > (best.an ?? 0) ? o
      : best,
    null,
  );
  const counts = top === null ? null : formatAlleleCounts(top);
  const mostCopies = top !== null && counts !== null
    ? { label: top.label, counts, af: top.af }
    : null;
  return {
    mostCopies,
    governs: Boolean(mostCopies && mostCopies.af !== null && mostCopies.af === ruleAf),
    ruleAf,
    ruleSource: frequencySourceLabel(evidence),
  };
}

/**
 * The dataset identifier of the local dbNSFP ingest, which merges the two gnomAD cohorts.
 */
export const LOCAL_GNOMAD_DATASET = "gnomad_r4_local";

/**
 * Name the gnomAD release the pipeline actually pinned.
 *
 * `gnomad_r4` is the GraphQL dataset enum (`server/services/external-api/gnomad.ts`) and `r4` is
 * gnomAD's own release token, but "v4" is the name gnomAD and every clinician uses for it — the
 * token is an API identifier, not a version to show a reader. The defect this replaced was the
 * PATCH claim: surfaces printed "v4.0.0" and "v4.1.0" for the same query, neither read from
 * anywhere, and `gnomad_r4` is an alias that moves with the latest v4 minor. So the major release
 * is stated, and no minor is asserted.
 *
 * The local dbNSFP ingest is named rather than passed through: it reports ONE combined frequency
 * (`server/services/prediction/local-population.ts`), so attributing its
 * value to the exome cohort is wrong.
 */
export function gnomadReleaseLabel(dataset: string | null | undefined): string {
  if (!dataset) return "release not reported";
  const local = dataset === LOCAL_GNOMAD_DATASET;
  const base = local ? dataset.slice(0, -"_local".length) : dataset;
  // `gnomad_r4`, `gnomad_r3`, `gnomad_r2_1` — the major release is the part the code establishes.
  // Anything unrecognised is passed through rather than guessed at.
  const major = /^gnomad_r(\d+)/.exec(base);
  if (!major) return dataset;
  return local ? `v${major[1]} (local dbNSFP ingest)` : `v${major[1]}`;
}

/**
 * Classify the frequency using the rule engine's arithmetic and branch order.
 *
 * MIRRORS `server/services/prediction/acmg/criteria.ts` §2. The branch order is load-bearing and is
 * the reason this is one function rather than three ternaries at the call sites:
 *
 *   0. A build gnomAD does not serve WITHDRAWS the criterion — the coordinate was never queried, and
 *      the status it leaves behind is indistinguishable from a confirmed absence.
 *   1. A provider outage WITHDRAWS the criterion. It does not fall through to "absent".
 *   2. A query still in flight has not classified anything yet, so it also withdraws.
 *   3. The ancestry-grouped maximum outranks the global maximum (it is the more sensitive of the two).
 *   4. A confirmed absence is the number ZERO — a measurement, and one that satisfies PM2.
 *   5. ClinVar-submitted frequencies are the last resort, and only when no gnomAD reading exists.
 *   6. Otherwise the frequency is unknown and no criterion is reported.
 *
 * The band `pm2Ceiling < af <= tooCommonForDisorder` deliberately yields `none`: ACMG's BS1 is
 * "greater than expected for the disorder", which is a gene-specific judgement the frequency alone
 * cannot make. Reporting neither criterion is the honest answer; inventing BS1 there would be a
 * classification the engine does not perform.
 */
export function classifyAcmgFrequency(input: FrequencyEvidenceInput): FrequencyCriterion {
  const { gnomadFrequency = null, clinvar = null, serviceStatus = null, assembly = null } = input;
  const FREQ = THRESHOLDS.populationFrequency;

  const base = {
    usedGroupMax: false,
    fallback: false,
    absent: false,
    pm2Ceiling: null as number | null,
    inheritance: "unknown" as FrequencyCriterion["inheritance"],
    headline: null as string | null,
    predicate: null as string | null,
  };

  // 0. A build the source cannot serve. Tested first because the status this leaves behind is
  //    `not_found` — indistinguishable from a confirmed absence — so any later test would read it.
  const status = serviceStatus?.gnomadFrequency;
  // 0a. …and when that build is a FALLBACK (the GRCh38 lookup failed), say so: it is a lookup failure
  //     a re-run can fix, not a fact about the variant. Still withheld — nothing was queried.
  const locusFallback = fallbackRefusal(input);
  if (locusFallback) {
    return {
      ...base,
      code: "withheld",
      af: null,
      sourceId: null,
      statement: `Population-frequency evidence was withheld: ${locusFallback.sentence} No frequency criterion (PM2, BS1 or BA1) was applied.`,
    };
  }
  const buildRefusal =
    assembly && !sourceSupportsAssembly(GNOMAD_SOURCE, assembly)
      ? describeAssemblyRefusal(GNOMAD_SOURCE, assembly)
      : null;
  /**
   * A build gnomAD does not serve. Recognised from EITHER the payload's own status or the
   * coordinate's build: the server records `unsupported-build` when its gate refuses
   * (`core-data-fetcher.ts`), and the build alone is enough when a payload predates that status.
   * Both paths must withhold — reading this as an absence is what made the classifier award PM2 for a
   * variant no database had been queried about.
   */
  if (buildRefusal || status === "unsupported-build") {
    const reason =
      buildRefusal ??
      "this coordinate's genome build is not one gnomAD r4 serves, so gnomAD was never queried.";
    return {
      ...base,
      code: "withheld",
      af: null,
      sourceId: null,
      statement: `Population-frequency evidence was withheld: ${reason} No frequency criterion (PM2, BS1 or BA1) was applied.`,
    };
  }

  // 1/2. Withheld — an outage is not an absence, and a running query has decided nothing yet.
  if (status === "timeout" || status === "error") {
    return {
      ...base,
      code: "withheld",
      af: null,
      sourceId: null,
      statement: `Population-frequency evidence was withheld: the gnomAD query ${status === "timeout" ? "timed out" : "failed"}. No frequency criterion (PM2, BS1 or BA1) was applied.`,
    };
  }
  if (status === "pending") {
    return {
      ...base,
      code: "withheld",
      af: null,
      sourceId: null,
      statement:
        "The population-frequency query is still running, so no frequency criterion (PM2, BS1 or BA1) has been applied yet.",
    };
  }

  let af: number | null = null;
  let sourceId: FrequencyCriterion["sourceId"] = null;
  let usedGroupMax = false;
  let fallback = false;
  let absent = false;

  // 3/4. gnomAD: grouped maximum, then global maximum, then a confirmed absence.
  const groupMaxAF = finite(gnomadFrequency?.groupMaxAF);
  const globalMaxAF = finite(gnomadFrequency?.maxAF);
  if (groupMaxAF !== null) {
    af = groupMaxAF;
    sourceId = "gnomad-group";
    usedGroupMax = true;
    fallback = Boolean(gnomadFrequency?.groupMaxAFIsFallback);
  } else if (globalMaxAF !== null) {
    af = globalMaxAF;
    sourceId = "gnomad-group";
  } else if (status === "not_found") {
    af = 0;
    sourceId = "gnomad-group";
    absent = true;
  } else {
    // 5. ClinVar-submitted frequencies. Only a value that parses to a finite number is evidence:
    //    the wire type is `{ source: string; value: any }` (`external-api/clinvar.ts:18`), so a
    //    malformed value is reachable, and reading it as `0` would manufacture an "extremely rare"
    //    finding — with PM2 support — out of a broken record.
    const submitted = (clinvar?.alleleFrequencies ?? [])
      .map(f => finite(typeof f.value === "string" ? parseFloat(f.value) : f.value))
      .filter((v): v is number => v !== null);
    if (submitted.length > 0) {
      af = Math.max(...submitted);
      sourceId = "clinvar-submissions";
    }
  }

  // 6. Nothing to classify on.
  if (af === null) {
    return {
      ...base,
      code: "unknown",
      af: null,
      sourceId: null,
      statement:
        "No population frequency was available to classify — no gnomAD reading and no ClinVar-submitted frequency. No frequency criterion was applied.",
    };
  }

  // PM2's ceiling is inheritance-aware; without a pLI the engine reads dominant/unknown.
  const pli = finite(input.pli);
  const recessive = pli !== null && pli < FREQ.recessivePlI;
  const pm2Ceiling = recessive ? FREQ.extremelyRareRecessive : FREQ.extremelyRare;
  const inheritance: FrequencyCriterion["inheritance"] = recessive
    ? "recessive"
    : pli === null
      ? "unknown"
      : "dominant";

  const shared = { ...base, af, sourceId, usedGroupMax, fallback, absent };

  /**
   * Each branch states its clause ONCE, and the full sentence is composed from it. The headline and
   * the predicate are what a surface that already shows the value as a figure renders, so the
   * summary card no longer prints its own number twice — and the composed `statement` cannot
   * disagree with them, because it is built from them.
   */
  if (af > FREQ.standAloneBenign) {
    const headline = "Stand-alone benign";
    const predicate = `above the ${pct(FREQ.standAloneBenign, 1)} BA1 cut-point`;
    return {
      ...shared,
      code: "BA1",
      headline,
      predicate,
      statement: `${headline}: ${formatAlleleFrequency(af)} is ${predicate}.`,
    };
  }
  if (af > FREQ.tooCommonForDisorder) {
    const headline = "Too common for the disorder";
    const predicate = `above the ${pct(FREQ.tooCommonForDisorder, 1)} BS1 cut-point`;
    return {
      ...shared,
      code: "BS1",
      headline,
      predicate,
      statement: `${headline}: ${formatAlleleFrequency(af)} is ${predicate}.`,
    };
  }
  if (af <= pm2Ceiling) {
    const reading = recessive
      ? `recessive (pLI < ${FREQ.recessivePlI})`
      : inheritance === "dominant"
        ? `dominant (pLI ≥ ${FREQ.recessivePlI})`
        : "dominant/unknown (pLI not available)";
    const headline = "Extremely rare";
    const predicate = `at or below the ${pct(pm2Ceiling, 2)} PM2 ceiling for ${reading} inheritance`;
    return {
      ...shared,
      code: "PM2",
      pm2Ceiling,
      inheritance,
      headline,
      predicate,
      statement: `${headline}: ${formatAlleleFrequency(af)} is ${predicate}.`,
    };
  }

  const headline = "Between the cut-points";
  const predicate = `above the ${pct(pm2Ceiling, 2)} PM2 ceiling but below the ${pct(FREQ.tooCommonForDisorder, 1)} BS1 cut-point, so no frequency criterion applies`;
  return {
    ...shared,
    code: "none",
    pm2Ceiling,
    inheritance,
    headline,
    predicate,
    statement: `${formatAlleleFrequency(af)} sits ${predicate}.`,
  };
}

/**
 * What the engine recorded, read from its own criteria list.
 *
 * Deliberately a READ of the engine's output rather than a second implementation of its gates: the
 * weighting rules at `criteria.ts:77` are the engine's to own, and re-deriving them here is how a
 * surface starts certifying a decision the engine did not make.
 */
export function readAppliedCriterion(input: FrequencyEvidenceInput): FrequencyApplication {
  const supported = classifyAcmgFrequency(input);
  const weighting = input.acmgWeighting ?? null;
  /**
   * Only these weightings suppress frequency evidence, so only these may be named as the reason a
   * supported criterion went unrecorded. A `standard` run that records no PM2 has some other cause,
   * and this module cannot see what it is.
   */
  const weightingSuppresses = weighting === "strict-structural" || weighting === "conservative";
  const criteria = input.engineCriteria;
  if (!criteria) {
    return { code: null, known: false, suppressed: false, withheldByWeighting: false, weighting };
  }
  const recorded = criteria
    .map(c => (typeof c?.code === "string" ? c.code.toUpperCase() : ""))
    .find(code => code === "BA1" || code === "BS1" || code === "PM2") as
    | FrequencyApplication["code"]
    | undefined;
  const code = recorded ?? null;
  const supportsCriterion = supported.code === "BA1" || supported.code === "BS1" || supported.code === "PM2";
  return {
    code,
    known: true,
    suppressed: code === null && supportsCriterion,
    withheldByWeighting: code === null && supportsCriterion && weightingSuppresses,
    weighting,
  };
}

/**
 * The availability of a gnomAD dataset that holds no value.
 *
 * Reads the source status so an outage is reported as a provider error, and the build gate before
 * the status so a coordinate gnomAD never accepted is not reported as one it searched and found
 * nothing in. Both orderings are the whole point: before this, every missing value rendered as a
 * confirmed absence, so an outage and a gate refusal both made the tab assert the opposite of the
 * truth — the UI-side instance of the invariant `server/invariants.test.ts` enforces for the
 * classifier.
 *
 * The remaining cases are kept apart for the same reason. `not_found` is the server's own
 * determination that gnomAD answered and holds no record; a dataset that is simply empty because the
 * variant was seen in the other one is a weaker fact; and a status we cannot read at all is weaker
 * still, so it claims nothing about the variant.
 */
function gnomadAbsence(
  status: string | undefined,
  datasetLabel: string,
  buildRefusal: string | null,
): EvidenceAvailability {
  if (buildRefusal || status === "unsupported-build") {
    return resolveEvidenceAvailability({
      status: "live",
      refusal:
        buildRefusal ??
        "gnomAD r4 serves GRCh38 only; this coordinate's build is not one it accepts, so it was not queried.",
    });
  }
  if (status === "timeout" || status === "error") {
    return resolveEvidenceAvailability({
      status: "unavailable",
      message: `The gnomAD frequency query ${status === "timeout" ? "timed out" : "returned an error"}, so this dataset was not read.`,
    });
  }
  if (status === "pending") {
    return resolveEvidenceAvailability({ status: "pending" });
  }
  if (status === "not_found") {
    return resolveEvidenceAvailability({
      status: "live",
      message: `gnomAD holds no record of this variant in ${datasetLabel}.`,
    });
  }
  /**
   * The query SUCCEEDED (`ok`) but this one dataset carries no frequency for the variant — the
   * common shape for a variant seen in exomes but not genomes. The outcome WAS recorded, so the
   * sentence below must not claim otherwise; what is absent is this dataset's value, not the run.
   * The previous revision fell through to "no outcome was recorded for the query", a run-level
   * claim derived from a dataset-level absence.
   */
  if (status === "ok") {
    return resolveEvidenceAvailability({
      status: "live",
      message: `gnomAD returned no frequency for this variant in ${datasetLabel}.`,
    });
  }
  /**
   * No readable status. The pipeline did not record an outcome for this source, so the honest answer
   * is bounded to what is known — gnomAD reported no frequency — and asserts neither presence nor
   * absence. The previous revision fell through to "The variant is not present in gnomAD … for this
   * release", which is an unbounded absence claim from zero evidence, and named a release the same
   * card reports as "release not reported".
   */
  return resolveEvidenceAvailability({
    status: "live",
    message: `gnomAD reported no frequency for this variant in ${datasetLabel}, and no outcome was recorded for the query.`,
  });
}

/**
 * The availability of the ClinVar classification.
 *
 * ClinVar is a source like any other on this screen, and its fetch carries its own status
 * (`core-data-fetcher.ts`). Reading the record without it turned an outage into "no submitter has
 * classified it" — a negative clinical result manufactured from a failed request.
 *
 * The server records a negative either as the `not_found` status or as the sentinel classification
 * string ("Not found in ClinVar"). Both are a RECORDED outcome, so both get the sentence that says
 * what absence from ClinVar means; only a status we cannot read at all gets the weaker wording.
 */
function clinvarAvailability(
  classification: string | null,
  status: string | undefined,
): EvidenceAvailability {
  const recordedNegative = Boolean(classification && /not found/i.test(classification));
  if (classification && !recordedNegative) {
    // The resolver's `value` is a measured value; for ClinVar the measurement is the classification
    // string, which is either there or not, so the sentinel only encodes its presence.
    return resolveEvidenceAvailability({ value: 1 });
  }
  if (status === "timeout" || status === "error") {
    return resolveEvidenceAvailability({
      status: "unavailable",
      message: `The ClinVar query ${status === "timeout" ? "timed out" : "returned an error"}, so this variant's classification could not be read.`,
    });
  }
  if (status === "pending") return resolveEvidenceAvailability({ status: "pending" });
  if (recordedNegative || status === "not_found" || status === "ok") {
    // `ok` with no classification is a RECORDED outcome — the query succeeded and ClinVar returned
    // nothing classifiable (reachable on legacy/cached payloads whose record predates the
    // classification). It says the same thing as `not_found`, and it must NOT fall through to the
    // "no outcome was recorded" sentence below, which would be false for a status of `ok`.
    return resolveEvidenceAvailability({
      status: "live",
      message: "ClinVar holds no classification for this variant. Absence from ClinVar is not evidence of benignity — it means no submitter has classified it.",
    });
  }
  return resolveEvidenceAvailability({
    status: "live",
    message: "ClinVar reported no classification for this variant, and no outcome was recorded for the query.",
  });
}

/**
 * Why the All of Us row is empty, bounded to what the run actually established.
 *
 * The previous sentence — "The local All of Us frequency table holds no entry for this variant" — was
 * printed for every empty row, including deployments with no local table and lookups that never
 * finished. Each branch below states only what `aouLookup` recorded; a payload without the record gets
 * the one sentence that claims nothing about a table.
 */
export function aouAbsenceReason(lookup: AouLookup | null): { reason: string; fault: boolean } {
  if (!lookup) return { reason: "No All of Us frequency was returned for this variant.", fault: false };
  const remote = lookup.remoteDbnsfp === "not-reported" ? " and the dbNSFP record carried no All of Us counts" : "";
  switch (lookup.localTable) {
    case "absent":
      return { reason: `The local All of Us frequency table holds no entry for this variant${remote}.`, fault: false };
    case "not-installed":
      return {
        reason: `No All of Us frequency was returned: no local All of Us table is installed in this deployment${remote}.`,
        fault: false,
      };
    case "timed-out":
      return { reason: "The local All of Us lookup timed out on this run, so the table was not read — re-run to retry.", fault: true };
    case "failed":
      return { reason: "The local All of Us lookup failed on this run, so the table was not read — re-run to retry.", fault: true };
    default:
      return { reason: "No All of Us frequency was returned for this variant.", fault: false };
  }
}

/** Source lineage for All of Us, shared by observation datasets and the inspector rail.
 * Counts establish a reading, not which deployment/provider served it. An unbound fallback
 * cannot turn a legacy protein-row lookup into verified nucleotide-specific provenance.
 */
export function aouSourceLabel(lookup: AouLookup | null | undefined, locus?: LocusResultLike | null): string {
  const unbound = isFallbackLocus(locus) && !locus?.predictorData?.gnomadVariantId;
  if (!lookup || unbound) return "source not reported";
  if (lookup.localTable === "found") return "local frequency table";
  if (lookup.remoteDbnsfp === "found") return "remote dbNSFP";
  if (lookup.localTable === "absent") return "local frequency table (no entry)";
  if (lookup.localTable === "failed" || lookup.localTable === "timed-out") return "local frequency table (not read)";
  if (lookup.localTable === "not-installed") return "local table not installed";
  return "source not reported";
}

/** The one-line summary above the Source readings table when nothing was observed. */
export interface ReadingsSummary {
  kind: "none-observed" | "none-queried" | "partly-queried" | "pending";
  text: string;
}

/**
 * Summarise the empty Source readings card without overclaiming.
 *
 * The card used to print "No source reported this allele." whenever nothing was OBSERVED — whether or
 * not any source was asked. On a fallback-locus run gnomAD was never queried, and the line asserted an
 * absence nobody had looked for. Only a source that answered and held no record (`no-result`) counts
 * as having "reported" nothing; refused, failed and in-flight sources are counted apart.
 *
 * Returns null when at least one source has a value: the table then speaks for itself.
 */
export function summariseReadings(observations: ReadonlyArray<FrequencyObservation>): ReadingsSummary | null {
  if (observations.some(o => o.availability.hasValue)) return null;
  const answered = observations.filter(o => o.availability.state === "no-result" && o.queried !== false && o.availability.action !== "provide-allele").length;
  const pending = observations.filter(o => o.availability.state === "pending").length;
  const unqueried = observations.length - answered - pending;
  if (pending > 0 && answered === 0) {
    return { kind: "pending", text: "Population sources are still being queried." };
  }
  if (answered === 0) {
    return { kind: "none-queried", text: "No source could be queried for this allele, so population frequency was not assessed." };
  }
  if (unqueried > 0 || pending > 0) {
    const notRead = unqueried + pending;
    return {
      kind: "partly-queried",
      text: `No queried source reported this allele; ${notRead} ${notRead === 1 ? "source was" : "sources were"} not read.`,
    };
  }
  return { kind: "none-observed", text: "No source reported this allele." };
}

/**
 * Build the whole view: per-source observations, what the frequency supports, and what the engine did.
 */
export function buildFrequencyEvidence(input: FrequencyEvidenceInput): FrequencyEvidence {
  const {
    gnomadFrequency = null,
    aouFrequency = null,
    serviceStatus = null,
    clinvar = null,
    assembly = null,
  } = input;

  const gnomadStatus = serviceStatus?.gnomadFrequency;
  const buildRefusal =
    assembly && !sourceSupportsAssembly(GNOMAD_SOURCE, assembly)
      ? describeAssemblyRefusal(GNOMAD_SOURCE, assembly)
      : null;
  const fallback = fallbackRefusal(input);
  const rawDataset = gnomadFrequency?.dataset ?? (
    (gnomadStatus === "not_found" || gnomadStatus === "ok") && !buildRefusal && !fallback
      ? "gnomad_r4"
      : null
  );
  const dataset = gnomadReleaseLabel(rawDataset);
  const isLocalIngest = rawDataset === LOCAL_GNOMAD_DATASET;

  const gnomadObservation = (
    id: FrequencyObservation["id"],
    label: string,
    af: number | null,
    ac: number | null,
    an: number | null,
  ): FrequencyObservation => {
    // A measured 0 is a value; NaN/Infinity/undefined are not, and `finite` is what draws that line.
    const hasValue = finite(af) !== null;
    return {
      key: id,
      id,
      label,
      dataset,
      af: hasValue ? finite(af) : null,
      ac: finite(ac),
      an: finite(an),
      homozygotes: null,
      heterozygotes: null,
      queried: !fallback,
      availability: hasValue
        ? resolveEvidenceAvailability({ value: finite(af) })
        : fallback
          // Only a temporary lookup failure is a provider fault. Ambiguity needs input.
          ? resolveEvidenceAvailability({
              status: fallback.retryable ? "unavailable" : "live",
              message: fallback.sentence,
              inputRequired: fallback.recoveryAction === "provide-allele",
            })
          : gnomadAbsence(gnomadStatus, label.toLowerCase(), buildRefusal),
    };
  };

  /**
   * The local dbNSFP ingest reports ONE combined frequency
   * (`server/services/prediction/local-population.ts`), so it is one reading, not a genome reading and an exome
   * reading. Splitting it into two rows would print the same number twice and attribute a combined
   * figure to the exome cohort.
   */
  const observations: FrequencyObservation[] = isLocalIngest
    ? [
        gnomadObservation(
          "gnomad-local",
          "gnomAD (local dbNSFP, cohorts combined)",
          finite(gnomadFrequency?.maxAF ?? gnomadFrequency?.genomeAF),
          finite(gnomadFrequency?.genomeAC),
          finite(gnomadFrequency?.genomeAN),
        ),
      ]
    : [
        gnomadObservation(
          "gnomad-exomes",
          "Exomes",
          finite(gnomadFrequency?.exomeAF),
          finite(gnomadFrequency?.exomeAC),
          finite(gnomadFrequency?.exomeAN),
        ),
        gnomadObservation(
          "gnomad-genomes",
          "Genomes",
          finite(gnomadFrequency?.genomeAF),
          finite(gnomadFrequency?.genomeAC),
          finite(gnomadFrequency?.genomeAN),
        ),
      ];

  /**
   * All of Us.
   *
   * Only actual counts or a recorded lookup establish that this cohort was read. A missing lookup
   * must not count as an answered source or imply a local table exists; explicit failures retain
   * their fault/retry semantics. An input-required fallback explains the missing allele instead
   * of inventing an absence from a table that could not be queried.
   *
   * The frequency is derived from the counts, which is the only place in the payload it can come
   * from: the contract carries AC/AN/Het/Hom and no `af`. Every shape the contract permits is named
   * for what it actually withholds, and the counts the row does hold are still carried on it.
   */
  const aouAC = finite(aouFrequency?.aouAC);
  const aouAN = finite(aouFrequency?.aouAN);
  const aouHet = finite(aouFrequency?.aouHet);
  const aouHom = finite(aouFrequency?.aouHom);
  const aouAF = aouAC !== null && aouAN !== null && aouAN > 0 ? aouAC / aouAN : null;
  const aouHasEntry = aouAC !== null || aouAN !== null || aouHet !== null || aouHom !== null;

  const aouLookup = input.aouLookup ?? null;
  const aouUnbound = isFallbackLocus(input.locus) && !input.locus?.predictorData?.gnomadVariantId;
  const aouNeedsAllele = !aouHasEntry && aouUnbound && fallback?.recoveryAction === "provide-allele";
  const aouQueried = aouHasEntry || (!aouNeedsAllele && (
    aouLookup?.localTable === "found" || aouLookup?.localTable === "absent" || aouLookup?.remoteDbnsfp === "found"
  ));

  let aouReason: string;
  /** A lookup that did not finish is a fault with a remedy, not an absence. */
  let aouFault = false;
  if (!aouHasEntry) {
    const said = aouAbsenceReason(aouLookup);
    aouFault = said.fault;
    aouReason = aouNeedsAllele && !aouFault
      ? `All of Us frequency was not assessed: ${fallbackCause(assembly, false, locusFailureKind(input.locus))}`
      : said.reason;
  } else if (aouAC === null && aouAN === null) {
    aouReason =
      "All of Us reports genotype counts for this variant but no allele count or allele number, so no frequency can be derived.";
  } else if (aouAC === null) {
    aouReason =
      "All of Us reports an allele number for this variant but no allele count, so no frequency can be derived.";
  } else if (aouAN === null || aouAN === 0) {
    aouReason =
      "All of Us reports an allele count for this variant but no usable allele number, so no frequency can be derived.";
  } else {
    aouReason = "The local All of Us frequency table holds no entry for this variant.";
  }

  observations.push({
    key: "all-of-us",
    id: "all-of-us",
    label: "All of Us",
    dataset: `All of Us (${aouSourceLabel(aouLookup, input.locus)})`,
    queried: aouQueried,
    af: aouAF,
    ac: aouAC,
    an: aouAN,
    homozygotes: aouHom,
    heterozygotes: aouHet,
    availability:
      aouAF !== null
        ? resolveEvidenceAvailability({ value: aouAF })
        : resolveEvidenceAvailability({ status: aouFault ? "unavailable" : "live", message: aouReason, inputRequired: aouNeedsAllele && !aouFault }),
  });

  /**
   * ClinVar-submitted frequencies. Previously these were rendered inside the gnomAD card when
   * gnomAD had nothing, which attributed a ClinVar submission to gnomAD. They are their own
   * observations now — one row per submitter, so the per-source detail is not collapsed into a
   * single maximum — and the criterion's `sourceId` names ClinVar when it is what the engine read.
   */
  const submitted = (clinvar?.alleleFrequencies ?? [])
    .map(f => ({
      source: f.source ?? "ClinVar submission",
      value: finite(typeof f.value === "string" ? parseFloat(f.value) : f.value),
    }))
    .filter((f): f is { source: string; value: number } => f.value !== null);
  for (const [index, { source, value }] of submitted.entries()) {
    observations.push({
      key: `clinvar-submissions:${index}`,
      id: "clinvar-submissions",
      label: source,
      dataset: "ClinVar submitted frequencies",
      af: value,
      ac: null,
      an: null,
      homozygotes: null,
      heterozygotes: null,
      availability: resolveEvidenceAvailability({ value }),
    });
  }

  const clinvarClassification = clinvar?.classification ?? null;

  const contributing = observations.filter(o => o.availability.hasValue && o.af !== null);
  const runStates = observations.map(o => o.availability.state);

  return {
    criterion: classifyAcmgFrequency(input),
    applied: readAppliedCriterion(input),
    clinvar: {
      classification: clinvarClassification,
      availability: clinvarAvailability(clinvarClassification, serviceStatus?.clinvar),
    },
    observations,
    contributing,
    gnomadHomozygotes: finite(gnomadFrequency?.nHomozygous),
    hasProviderFault: runStates.includes("upstream-error"),
    retryable: runStates.includes("upstream-error") || Boolean(fallback?.retryable),
    recoveryAction: fallback?.recoveryAction === "provide-allele"
      ? "provide-allele"
      : runStates.includes("upstream-error") || fallback?.retryable ? "retry" : null,
    hasPendingSource: runStates.includes("pending"),
    homozygoteCriterion: {
      code: "BS2",
      recorded: input.engineCriteria
        ? input.engineCriteria.some(c => typeof c?.code === "string" && c.code.toUpperCase() === "BS2")
        : null,
    },
  };
}

/**
 * The sentence a surface renders to explain an observation that holds no value.
 *
 * The recorded reason when the pipeline established one, the canonical state label otherwise —
 * never a phrase written at the call site. Two surfaces rendering the same observation therefore
 * cannot disagree about why it is empty, and no surface can invent a cause the pipeline never
 * recorded.
 */
export function observationAbsence(observation: FrequencyObservation): string {
  const { reason, label } = observation.availability;
  return reason ?? label ?? ENGINE_STATE_LABELS["no-result"];
}
