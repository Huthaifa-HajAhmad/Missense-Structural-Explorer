/**
 * frequencyEvidence.ts — what the population-frequency sources hold, and what the rule engine did with it.
 *
 * WHY THIS MODULE EXISTS
 * ----------------------
 * The Population Frequencies tab described the same three sources from a hand-written copy of the
 * facts, and that copy was wrong in ways a reader could not detect:
 *
 *   • **The tab showed counts, never a frequency.** It printed "Exomes (v4.0) 8 / Allele Number
 *     1,459,156" while the panel beside it quoted allele-frequency thresholds (PM2/BS1/BA1) and the
 *     engine classified on `groupMaxAF`. The one number the verdict turns on appeared nowhere.
 *   • **Any missing gnomAD value read as "Absent from gnomAD population database (rare/novel
 *     variant)".** A provider timeout and a confirmed absence were the same render, so the tab
 *     asserted the opposite of the truth during an outage — the UI-side instance of the invariant
 *     `server/invariants.test.ts` enforces for the classifier ("timeout never implies absence").
 *     Nothing in the component read `serviceStatus`, so the distinction was not merely misworded; it
 *     was unavailable to the code making the claim.
 *   • **The panel's cut-points were hand-written.** It printed "BS1 … MAF > 0.1%" beside an engine
 *     branching at 1%. The two numbers could not be reconciled by the reader, and neither was
 *     generated by the rule it described.
 *
 * WHAT IT GUARANTEES
 * ------------------
 * 1. **Absence is classified, never worded.** Every source's missing value goes through
 *    `resolveEvidenceAvailability`, so its label comes from the canonical engine vocabulary and its
 *    "why" is only ever a reason the pipeline actually recorded. A timeout cannot be rendered as an
 *    absence because the timeout branch is tested first; a build the source does not serve cannot be
 *    rendered as an absence because the build gate is tested before the status.
 * 2. **The cut-points are the engine's.** They are read from `THRESHOLDS.populationFrequency`, the
 *    same constant `server/services/prediction/acmg/criteria.ts` branches on, and `criterion` mirrors
 *    that engine's branch ORDER and its arithmetic — including the band between PM2's ceiling and
 *    BS1's floor, which yields no criterion at all rather than a fabricated one.
 * 3. **What the engine APPLIED is read, not recomputed.** `criterion` is what the frequency
 *    supports; `applied` is what the engine recorded. They differ legitimately — the ACMG weighting
 *    is user-selectable and suppresses PM2 under `strict-structural`, and under `conservative` when
 *    ClinVar is not pathogenic (`criteria.ts:77`) — so a surface that showed only `criterion` would
 *    report a pathogenic criterion the engine had withheld. Both are exposed and `applied.suppressed`
 *    names the disagreement.
 *
 * BOUNDARY CONTRACT
 * -----------------
 * Imported by `src/` surfaces. Pure: imports only from `src/shared/` (enforced by
 * scripts/check-boundaries.ts).
 */
