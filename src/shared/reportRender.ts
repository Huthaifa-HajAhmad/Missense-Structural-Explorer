/**
 * reportRender.ts — the Report document as plain text, one html file and JSON.
 *
 * These are renderings of `ReportDocument` and nothing else. Each carries exactly the blocks the
 * author left in (`exportedBlocks`), marks edited blocks, and ends with the same footer (research use,
 * generated-at, what was left out, Document ID). The html file is self-contained: inline styles, no
 * script, no network, so it opens anywhere and prints to PDF through the browser's own dialog.
 *
 * The palette below is the exported file's own. It cannot use the app's `--cs-*` tokens because the
 * file is read outside the app, so hex is deliberate here (and only here).
 */
import {
  exportedBlocks,
  parseProse,
  proseToPlain,
  type ProseNode,
  type ProseRun,
  type ReportBlock,
  type ReportDocument,
  type ReportTable,
} from "./reportDocument.ts";

export const REPORT_JSON_SCHEMA = "mse.report-document/1";

// ── Plain text ───────────────────────────────────────────────────────────────────────────────────

function padCells(table: ReportTable): string[] {
  const all = [table.headers, ...table.rows];
  const widths = table.headers.map((_, c) => Math.min(48, Math.max(...all.map(r => (r[c] ?? "").length))));
  const fmt = (row: string[]) => row.map((cell, c) => (c === row.length - 1 ? cell : (cell ?? "").padEnd(widths[c]))).join("  ");
  return [fmt(table.headers), ...table.rows.map(fmt)];
}

function textBlock(b: ReportBlock, index: number): string {
  const out: string[] = [`${index}. ${b.title.toUpperCase()}${b.edited ? "  [edited by the author]" : ""}`];
  if (b.verdict) out.push(`Classification: ${b.verdict.text ?? "Not classified"} (rule engine${b.verdict.weighting ? `, ${b.verdict.weighting} weighting` : ""})`);
  for (const f of b.facts) out.push(`${f.label}: ${f.value}`);
  if (b.text.trim()) out.push("", proseToPlain(b.text));
  if (b.table) out.push("", ...padCells(b.table));
  if (b.caption) out.push("", `Note: ${b.caption}`);
  return out.join("\n");
}

export function renderReportText(doc: ReportDocument): string {
  const lines: string[] = [doc.title, doc.footer.useStatement, ""];
  if (doc.meta.preparedBy) lines.push(`Prepared by: ${doc.meta.preparedBy}`);
  if (doc.meta.caseRef) lines.push(`Case reference: ${doc.meta.caseRef}`);
  const blocks = exportedBlocks(doc);
  blocks.forEach((b, i) => lines.push("", "-".repeat(60), textBlock(b, i + 1)));
  lines.push("", "=".repeat(60));
  lines.push(`Generated by ${doc.footer.app}${doc.footer.generatedAt ? ` on ${doc.footer.generatedAt.slice(0, 10)}` : ""}.`);
  if (doc.footer.omitted.length) lines.push(`Not included by the author: ${doc.footer.omitted.join("; ")}.`);
  lines.push(`Document ID ${doc.footer.documentId}: a checksum of this text; it detects later changes and does not prove authorship.`);
  return lines.join("\n");
}

// ── HTML ─────────────────────────────────────────────────────────────────────────────────────────

export const esc = (s: string): string =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");

const runsHtml = (runs: ProseRun[]) => runs.map(r => (r.bold ? `<strong>${esc(r.text)}</strong>` : esc(r.text))).join("");

function proseHtml(text: string): string {
  return parseProse(text)
    .map((n: ProseNode) =>
      n.type === "ul" ? `<ul>${n.items.map(i => `<li>${runsHtml(i)}</li>`).join("")}</ul>`
      : n.type === "h" ? `<h3>${runsHtml(n.runs)}</h3>`
      : `<p>${runsHtml(n.runs)}</p>`
    )
    .join("");
}

function tableHtml(t: ReportTable): string {
  const num = new Set(t.numeric ?? []);
  return `<table><thead><tr>${t.headers.map((h, c) => `<th${num.has(c) ? ' class="n"' : ""}>${esc(h)}</th>`).join("")}</tr></thead><tbody>${t.rows
    .map(r => `<tr>${r.map((cell, c) => `<td${num.has(c) ? ' class="n"' : ""}>${esc(cell)}</td>`).join("")}</tr>`)
    .join("")}</tbody></table>`;
}

function chipsHtml(b: ReportBlock): string {
  return b.chips.map(c => `<span class="chip ${c.tone}${c.dashed ? " dashed" : ""}">${esc(c.label)}</span>`).join("");
}

function ladderHtml(b: ReportBlock): string {
  const v = b.verdict;
  if (!v) return "";
  return `<div class="ladder" role="img" aria-label="ACMG tier: ${esc(v.tier ?? "not classified")}">${v.tiers
    .map((t, i) => `<div class="tier${i === v.tierIndex ? " on" : ""}">${esc(t)}</div>`)
    .join("")}</div>`;
}

function blockHtml(b: ReportBlock): string {
  const facts = b.facts.length
    ? `<dl>${b.facts.map(f => `<div><dt>${esc(f.label)}</dt><dd${f.mono ? ' class="mono"' : ""}>${esc(f.value)}</dd></div>`).join("")}</dl>`
    : "";
  const verdict = b.verdict
    ? `<p class="verdict">${esc(b.verdict.text ?? "Not classified")}</p>${ladderHtml(b)}`
    : "";
  return `<section class="block" id="b-${esc(b.key)}"><h2>${esc(b.title)} ${chipsHtml(b)}</h2>${verdict}${facts}${b.text.trim() ? `<div class="prose">${proseHtml(b.text)}</div>` : ""}${b.table ? tableHtml(b.table) : ""}${b.caption ? `<p class="cap">${esc(b.caption)}</p>` : ""}</section>`;
}

