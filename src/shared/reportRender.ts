export function renderReportHtml(doc: ReportDocument): string {
  const blocks = exportedBlocks(doc);
  const who = [doc.meta.preparedBy ? `Prepared by ${esc(doc.meta.preparedBy)}` : "", doc.meta.caseRef ? `Case reference ${esc(doc.meta.caseRef)}` : ""]
    .filter(Boolean)
    .join(" · ");
  const stamp = doc.footer.generatedAt ? ` on ${esc(doc.footer.generatedAt.slice(0, 10))}` : "";
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${esc(doc.title)}</title><style>${REPORT_CSS}</style></head><body><main><header><h1>${esc(doc.title)}</h1><p class="use">${esc(doc.footer.useStatement)}</p>${who ? `<p class="who">${who}</p>` : ""}</header>${blocks.map(blockHtml).join("")}<footer><p>Generated by ${esc(doc.footer.app)}${stamp}.</p>${doc.footer.omitted.length ? `<p>Not included by the author: ${esc(doc.footer.omitted.join("; "))}.</p>` : ""}<p>Document ID <span class="mono">${esc(doc.footer.documentId)}</span>: a checksum of the text above. It detects later changes and does not prove authorship.</p></footer></main></body></html>`;
}

// ── JSON ─────────────────────────────────────────────────────────────────────────────────────────

/**
 * The document as data: what was included, the drafted text, and the author's text where there is
 * one. The evidence bundle (payload and provenance manifest) is a separate file on purpose.
 */
export function renderReportJson(doc: ReportDocument): Record<string, unknown> {
  return {
    schema: REPORT_JSON_SCHEMA,
    generatedAt: doc.footer.generatedAt,
    documentId: doc.footer.documentId,
    title: doc.title,
    subject: doc.subject,
    preparedBy: doc.meta.preparedBy || null,
    caseReference: doc.meta.caseRef || null,
    useStatement: doc.footer.useStatement,
    weighting: doc.footer.weighting,
    omittedByAuthor: doc.footer.omitted,
    blocks: exportedBlocks(doc).map(b => ({
      key: b.key,
      title: b.title,
      status: b.status,
      edited: b.edited,
      staleEdit: b.stale,
      countedCriteria: b.counted,
      drafted: b.drafted,
      authorText: b.edited ? b.text : null,
      facts: b.facts,
      table: b.table,
      caption: b.caption,
    })),
  };
}
