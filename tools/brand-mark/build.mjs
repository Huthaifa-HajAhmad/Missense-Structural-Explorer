/**
 * Regenerates every brand-mark artefact from `geometry.mjs`:
 *
 *   src/components/ui/BrandMark.tsx   the in-app mark (colours via CSS variables)
 *   public/favicon.svg                the tab icon (16–24px drawing, literal colours)
 *   public/favicon-32.png             PNG fallback          ┐ only with --png: these need a
 *   public/apple-touch-icon.png       iOS home screen, 180  ┘ Chromium to rasterise
 *
 *   node tools/brand-mark/build.mjs [--png]
 *
 * Edit the geometry, not the outputs: all four are generated.
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { spawn } from "node:child_process";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { brandMarkShapes, simplifyPath, num } from "./geometry.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

/** Brand colours on the clay tile. `back` is the far side of each helix turn: white at ~70% over clay. */
export const CLAY = { bg: "#C46849", body: "#FFFFFF", back: "#EFC9BB", hit: "#191816" };
const VIEWBOX = "-4 -4 72 72";

/* ── SVG markup (favicons) ── */
function svgElements(shapes) {
  return shapes
    .map((s) => {
      const d = simplifyPath(s.d);
      if (s.tag === "polygon") {
        return `<path d="${d}" fill="${s.fill}" stroke="${s.stroke}" stroke-width="${num(s.width)}" stroke-linejoin="round" paint-order="stroke"/>`;
      }
      return `<path d="${d}" fill="none" stroke="${s.stroke}" stroke-width="${num(s.width)}" stroke-linecap="${s.cap}" stroke-linejoin="round"/>`;
    })
    .join("");
}
function tileSvg(shapes, { rounded }) {
  const rect = rounded
    ? `<rect x="-4" y="-4" width="72" height="72" rx="17" fill="${CLAY.bg}"/>`
    : `<rect x="-4" y="-4" width="72" height="72" fill="${CLAY.bg}"/>`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEWBOX}">${rect}${svgElements(shapes)}</svg>\n`;
}

/* ── JSX (component) ── */
function jsxElements(shapes, indent) {
  const key = { [CSSVARS.bg]: "C.bg", [CSSVARS.body]: "C.body", [CSSVARS.back]: "C.back", [CSSVARS.hit]: "C.hit" };
  return shapes
    .map((s) => {
      const d = simplifyPath(s.d);
      if (s.tag === "polygon") {
        return `${indent}<path d="${d}" fill={${key[s.fill]}} stroke={${key[s.stroke]}} strokeWidth={${num(s.width)}} strokeLinejoin="round" paintOrder="stroke" />`;
      }
      return `${indent}<path d="${d}" fill="none" stroke={${key[s.stroke]}} strokeWidth={${num(s.width)}} strokeLinecap="${s.cap}" strokeLinejoin="round" />`;
    })
    .join("\n");
}
const CSSVARS = { bg: "__bg__", body: "__body__", back: "__back__", hit: "__hit__" };

const component = `/* GENERATED by tools/brand-mark/build.mjs from tools/brand-mark/geometry.mjs — do not edit by hand. */
import React from "react";

/**
 * The Missense & Fold mark: an α-helix, a loop and a β-strand arrow, with one front turn of the
 * helix in the accent colour — the substituted residue, coloured into the fold.
 *
 * The SVG is the whole tile's artwork (viewBox ${VIEWBOX} carries the inset), so it fills its
 * container edge to edge. The container paints the tile; \`--bm-bg\` must match it, because the
 * gaps that separate crossing strands are drawn in that colour.
 *
 * Below 32px a separate, heavier drawing is used rather than a scaled copy: thin back strokes and
 * narrow gaps disappear at favicon sizes.
 */
const C = {
  bg: "var(--bm-bg, ${CLAY.bg})",
  body: "var(--bm-body, ${CLAY.body})",
  back: "var(--bm-back, ${CLAY.back})",
  hit: "var(--bm-hit, ${CLAY.hit})",
};

const LARGE = (
  <>
${jsxElements(brandMarkShapes(CSSVARS), "    ")}
  </>
);

const SMALL = (
  <>
${jsxElements(brandMarkShapes(CSSVARS, { small: true }), "    ")}
  </>
);

interface BrandMarkProps {
  /** Rendered size in px; also picks the drawing (below 32px uses the small cut). */
  size: number;
  className?: string;
}

export function BrandMark({ size, className }: BrandMarkProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="${VIEWBOX}"
      className={className}
      aria-hidden="true"
      focusable="false"
    >
      {size < 32 ? SMALL : LARGE}
    </svg>
  );
}

export default BrandMark;
`;

writeFileSync(path.join(root, "src/components/ui/BrandMark.tsx"), component);
mkdirSync(path.join(root, "public"), { recursive: true });
const faviconSvg = tileSvg(brandMarkShapes(CLAY, { small: true }), { rounded: true });
writeFileSync(path.join(root, "public/favicon.svg"), faviconSvg);
console.log("brand-mark: wrote src/components/ui/BrandMark.tsx and public/favicon.svg");

if (process.argv.includes("--png")) {
  await rasterise([
    { file: "public/favicon-32.png", px: 32, svg: tileSvg(brandMarkShapes(CLAY), { rounded: true }) },
    // iOS masks the corners itself, so the touch icon is a full-bleed square.
    { file: "public/apple-touch-icon.png", px: 180, svg: tileSvg(brandMarkShapes(CLAY), { rounded: false }) },
  ]);
}

/** Screenshots each SVG at its exact pixel size through a headless Chromium's DevTools protocol. */
async function rasterise(jobs) {
  const candidates = [
    process.env.GEOMETRY_BROWSER,
    process.env.CHROME_PATH,
    "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
    "C:/Program Files/Microsoft/Edge/Application/msedge.exe",
    "C:/Program Files/Google/Chrome/Application/chrome.exe",
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/usr/bin/google-chrome",
    "/usr/bin/chromium",
  ].filter(Boolean);
  const browser = candidates.find((c) => existsSync(c));
  if (!browser) {
    console.error("brand-mark: no Chromium found for --png (set CHROME_PATH)");
    process.exit(2);
  }
  const port = 9300 + Math.floor(Math.random() * 400);
  const profile = path.join(root, "tools/brand-mark/.browser-profile");
  const proc = spawn(browser, ["--headless=new", "--disable-gpu", "--no-first-run", "--force-device-scale-factor=1",
    `--user-data-dir=${profile}`, `--remote-debugging-port=${port}`, "about:blank"]);
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  let targets;
  for (let i = 0; i < 50 && !targets; i++) {
    try { targets = await (await fetch(`http://127.0.0.1:${port}/json`)).json(); } catch { await sleep(200); }
  }
  const ws = new WebSocket(targets.find((t) => t.type === "page").webSocketDebuggerUrl);
  await new Promise((r) => ws.addEventListener("open", r));
  let id = 0;
  const pending = new Map();
  ws.addEventListener("message", (e) => {
    const m = JSON.parse(e.data);
    if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); }
  });
  const send = (method, params = {}) => new Promise((r) => { const n = ++id; pending.set(n, r); ws.send(JSON.stringify({ id: n, method, params })); });
  await send("Emulation.setDefaultBackgroundColorOverride", { color: { r: 0, g: 0, b: 0, a: 0 } });
  for (const job of jobs) {
    const html = `<html><body style="margin:0;background:transparent"><img src="data:image/svg+xml;base64,${Buffer.from(job.svg).toString("base64")}" width="${job.px}" height="${job.px}" style="display:block"></body></html>`;
    await send("Page.navigate", { url: `data:text/html;base64,${Buffer.from(html).toString("base64")}` });
    await sleep(400);
    const shot = await send("Page.captureScreenshot", { format: "png", clip: { x: 0, y: 0, width: job.px, height: job.px, scale: 1 } });
    writeFileSync(path.join(root, job.file), Buffer.from(shot.result.data, "base64"));
    console.log(`brand-mark: wrote ${job.file}`);
  }
  await send("Browser.close").catch(() => {});
  ws.close();
  proc.kill();
}
